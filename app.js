// تُحمّل جميع الجداول في استدعاء واحد لتكون Google Sheets المصدر الوحيد للبيانات.
function تحميل_البيانات() {
  _بيانات_كاملة_محملة = false;
  تحميل_كل_البيانات_دفعة_واحدة();
}

// ====== تحميل كل البيانات دفعة واحدة ======
var _بيانات_كاملة_محملة = false;
var _تحميل_كامل_قيد_التنفيذ = false;
function تحميل_كل_البيانات_دفعة_واحدة() {
  if (_بيانات_كاملة_محملة || _تحميل_كامل_قيد_التنفيذ) return;
  _تحميل_كامل_قيد_التنفيذ = true;
  إظهار_تحميل('جاري تحميل قاعدة البيانات الرسمية...');
  var المحاولة = 0;
  var الحد_الأقصى_للمحاولات = 4;

  function إنهاء_بالفشل() {
    _تحميل_كامل_قيد_التنفيذ = false;
    وضع_الاتصال = false;
    بيانات_الاسطول_المحلية = [];
    بيانات_الرصد = []; بيانات_الحوادث = []; بيانات_الصيانة_الوقائية = []; بيانات_تغيير_الزيت = [];
    تحديث_لوحة_القائد();
    تحديث_حالة_الاتصال();
    إخفاء_تحميل();
  }

  function معالجة_النجاح(استجابة) {
    _بيانات_كاملة_محملة = true;
    _تحميل_كامل_قيد_التنفيذ = false;
    وضع_الاتصال = true;
    بيانات_الاسطول_المحلية = Array.isArray(استجابة.fleet) ? استجابة.fleet : [];
    بيانات_الرصد = تطبيع_مجموعة_قادمة(Array.isArray(استجابة.tracking) ? استجابة.tracking : [], 'رصد');
    بيانات_الحوادث = تطبيع_مجموعة_قادمة(Array.isArray(استجابة.accidents) ? استجابة.accidents : [], 'حوادث');
    بيانات_الصيانة_الوقائية = تطبيع_مجموعة_قادمة(Array.isArray(استجابة.maintenance) ? استجابة.maintenance : [], 'صيانة');
    بيانات_تغيير_الزيت = Array.isArray(استجابة.oil) ? استجابة.oil : [];
    ملء_قوائم_اللوحات();
    تحديث_قوائم_من_البيانات_الرسمية();
    تحديث_جدول_الحوادث();
    تحديث_جدول_الصيانة();
    تحديث_جدول_تغيير_الزيت();
    تحديث_لوحة_القائد();
    فحص_تنبيهات_الزيت();
    تحديث_حالة_الاتصال();
    إخفاء_تحميل();
  }

  function طلب_جديد() {
    المحاولة++;
    var اسم_callback = 'fleetCallback' + Date.now() + Math.floor(Math.random() * 1000);
    var انتهى = false;
    function فشل_الطلب() {
      if (انتهى) return;
      انتهى = true;
      try { delete window[اسم_callback]; } catch(e) {}
      if (المحاولة < الحد_الأقصى_للمحاولات) {
        setTimeout(طلب_جديد, 900 * المحاولة);
      } else {
        إنهاء_بالفشل();
      }
    }
    window[اسم_callback] = function(استجابة) {
      if (انتهى) return;
      انتهى = true;
      try { delete window[اسم_callback]; } catch(e) {}
      if (استجابة && (استجابة.status === 'success' || استجابة.fleet !== undefined)) {
        try { معالجة_النجاح(استجابة); }
        catch (خطأ) { إنهاء_بالفشل(); }
      } else {
        if (المحاولة < الحد_الأقصى_للمحاولات) setTimeout(طلب_جديد, 900 * المحاولة);
        else إنهاء_بالفشل();
      }
    };
    var script = document.createElement('script');
    script.src = SCRIPT_URL + '?action=dashboard&callback=' + اسم_callback + '&ts=' + Date.now() + '&attempt=' + المحاولة;
    script.onerror = فشل_الطلب;
    document.head.appendChild(script);
    setTimeout(فشل_الطلب, 16000);
  }
  طلب_جديد();
}

// ====== تحميل مرحلي للسجلات الكبيرة ======
var تحميل_مرحلي = { رصد: false, زيت: false };
function تحميل_سجلات_حديثة(اسم_الشيت, النوع) {
  if (!وضع_الاتصال || تحميل_مرحلي[النوع]) return;
  تحميل_مرحلي[النوع] = true;
  var اسم_callback = 'cb_page_' + النوع + '_' + Date.now();
  window[اسم_callback] = function(استجابة) {
    try { delete window[اسم_callback]; } catch(e) {}
    تحميل_مرحلي[النوع] = false;
    if (!استجابة || استجابة.status !== 'success' || !Array.isArray(استجابة.rows)) return;
    var صفوف = استجابة.rows.slice().reverse();
    if (النوع === 'زيت') {
      بيانات_تغيير_الزيت = صفوف;
      تحديث_جدول_تغيير_الزيت();
      فحص_تنبيهات_الزيت();
    } else if (النوع === 'رصد') {
      بيانات_الرصد = تطبيع_مجموعة_قادمة(صفوف, 'رصد');
    }
    تحديث_لوحة_القائد();
  };
  var script = document.createElement('script');
  script.src = SCRIPT_URL + '?action=page&sheet=' + encodeURIComponent(اسم_الشيت) + '&limit=300&callback=' + اسم_callback + '&ts=' + Date.now();
  script.onerror = function() { try { delete window[اسم_callback]; } catch(e) {} تحميل_مرحلي[النوع] = false; };
  document.head.appendChild(script);
}

// ====== تحميل شيت واحد (للتوافق) ======
function تحميل_شيت(اسم_الشيت, دالة_الاستجابة) {
  // استخدام getAll بدلاً من get لأن السكريبت المنشور يدعمها
  var اسم_callback = 'cb_' + اسم_الشيت.replace(/\s/g,'_') + '_' + Date.now();
  window[اسم_callback] = function(استجابة) {
    try { delete window[اسم_callback]; } catch(e) {}
    if (استجابة && (استجابة.status === 'success' || استجابة.fleet !== undefined)) {
      // تحديد البيانات المطلوبة حسب اسم الشيت
      var خريطة = {
        'الأسطول': 'fleet',
        'رصد المركبات': 'tracking',
        'الحوادث': 'accidents',
        'الصيانة الوقائية': 'maintenance',
        'تغيير الزيت': 'oil'
      };
      var مفتاح = خريطة[اسم_الشيت];
      دالة_الاستجابة(مفتاح && استجابة[مفتاح] ? استجابة[مفتاح] : []);
    } else {
      دالة_الاستجابة(null);
    }
  };
  var script = document.createElement('script');
  script.src = SCRIPT_URL + '?action=getAll&callback=' + اسم_callback;
  script.onerror = function() {
    try { delete window[اسم_callback]; } catch(e) {}
    دالة_الاستجابة(null);
  };
  document.head.appendChild(script);
  setTimeout(function() {
    if (window[اسم_callback]) {
      try { delete window[اسم_callback]; } catch(e) {}
      دالة_الاستجابة(null);
    }
  }, 15000);
}

// ====== التواصل مع Google Sheets ======
function تنفيذ_طلب_شيت(إجراء, اسم_الشيت, بيانات_الصف, دالة_الاستجابة) {
  var اسم_callback = 'sheet_' + إجراء + '_' + Date.now() + '_' + Math.floor(Math.random() * 1000);
  var مكتمل = false;
  function إنهاء(استجابة) {
    if (مكتمل) return;
    مكتمل = true;
    try { delete window[اسم_callback]; } catch(e) {}
    if (دالة_الاستجابة) دالة_الاستجابة(استجابة);
  }
  window[اسم_callback] = إنهاء;
  var script = document.createElement('script');
  script.src = SCRIPT_URL + '?action=' + encodeURIComponent(إجراء) +
    '&sheet=' + encodeURIComponent(اسم_الشيت || '') +
    '&data=' + encodeURIComponent(JSON.stringify(بيانات_الصف || {})) +
    '&callback=' + اسم_callback;
  script.onerror = function() { إنهاء({status: 'error', message: 'تعذر الاتصال بخدمة Google Sheets'}); };
  document.head.appendChild(script);
  setTimeout(function() {
    if (!مكتمل) إنهاء({status: 'error', message: 'انتهت مهلة الاتصال بخدمة Google Sheets'});
  }, 15000);
}

// ====== حفظ سجل جديد في الشيت ======
function حفظ_في_شيت(اسم_الشيت, بيانات_الصف, دالة_الاستجابة) {
  تنفيذ_طلب_شيت('add', اسم_الشيت, بيانات_الصف, دالة_الاستجابة);
}

// ====== تحديث سجل قائم في الشيت دون تكراره ======
function تحديث_في_شيت(اسم_الشيت, بيانات_الصف, دالة_الاستجابة) {
  تنفيذ_طلب_شيت('update', اسم_الشيت, بيانات_الصف, دالة_الاستجابة);
}

