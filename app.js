function تحديث_حالة_حادث(رقم_الطلب, حالة_جديدة) {
  var حادث = null;
  for (var i = 0; i < بيانات_الحوادث.length; i++) {
    if (بيانات_الحوادث[i]['رقم_الطلب'] === رقم_الطلب) { حادث = بيانات_الحوادث[i]; break; }
  }
  if (!حادث) return;
  حادث['الحالة'] = حالة_جديدة;
  حادث['حالة_الإنجاز'] = (حالة_جديدة === 'مغلق' || حالة_جديدة === 'منجز') ? 'منجز' : 'غير منجز';
  حادث['تاريخ_التحديث'] = new Date().toLocaleString('ar-SA');
  تحديث_في_شيت('الحوادث', حادث, function(استجابة) {
    if (استجابة && استجابة.status === 'success') {
      إظهار_رسالة('تم تحديث الحادث إلى: ' + حالة_جديدة, 'نجاح');
    } else {
      إظهار_رسالة('تم تحديث الحادث في الواجهة فقط؛ يرجى نشر سكربت الربط الإصدار 6 لحفظه في Google Sheets.', 'تحذير');
    }
  });
  تحديث_جدول_الحوادث();
  تحديث_لوحة_القائد();
}

