function قيم_فريدة_رسمية(صفوف, حقل) {
  var قيم = [];
  (صفوف || []).forEach(function(صف) {
    var قيمة = String((صف || {})[حقل] || '').trim();
    if (قيمة && قيم.indexOf(قيمة) === -1) قيم.push(قيمة);
  });
  return قيم.sort();
}

