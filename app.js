function قيمة_رقمية(قيمة) {
  var رقم = parseInt(String(قيمة === undefined || قيمة === null ? '' : قيمة).replace(/[^0-9.-]/g, ''), 10);
  return isNaN(رقم) ? 0 : رقم;
}

function تاريخ_صالح(قيمة) {
  if (!قيمة) return null;
  if (Object.prototype.toString.call(قيمة) === '[object Date]' && !isNaN(قيمة.getTime())) return قيمة;
  var نص = String(قيمة).trim();
  var تاريخ = /^\d{4}-\d{2}-\d{2}$/.test(نص) ? new Date(نص + 'T00:00:00') : new Date(نص);
  return isNaN(تاريخ.getTime()) ? null : تاريخ;
}

function ترميز_HTML(قيمة) {
  return String(قيمة === undefined || قيمة === null ? '' : قيمة)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#039;');
}

