function حالة_زيت_الأسطول() {
  var مصدر = مصدر_الأسطول();
  var حسب_اللوحة = {};
  var أحدث_تغيير = {};
  var أحدث_رصد = {};
  var اليوم = new Date();

  بيانات_تغيير_الزيت.forEach(function(سجل) {
    var رقم = سجل['رقم_اللوحة'];
    if (!رقم) return;
    var تاريخ = تاريخ_صالح(سجل['التاريخ']) || تاريخ_صالح(سجل['وقت_الإدخال']);
    if (!أحدث_تغيير[رقم] || (تاريخ && تاريخ > أحدث_تغيير[رقم].تاريخ)) {
      أحدث_تغيير[رقم] = { تاريخ: تاريخ, قراءة: قيمة_رقمية(سجل['قراءة_العداد']) };
    }
  });
  بيانات_الرصد.forEach(function(سجل) {
    var رقم = سجل['رقم_اللوحة'];
    if (!رقم) return;
    var تاريخ = تاريخ_صالح(سجل['التاريخ']) || تاريخ_صالح(سجل['وقت_الإدخال']);
    if (!أحدث_رصد[رقم] || (تاريخ && تاريخ > أحدث_رصد[رقم].تاريخ)) {
      أحدث_رصد[رقم] = { تاريخ: تاريخ, قراءة: قيمة_رقمية(سجل['قراءة_العداد']) };
    }
  });

  مصدر.forEach(function(مركبة) {
    var رقم = مركبة['رقم_اللوحة'] || (Array.isArray(مركبة) ? مركبة[0] : '');
    if (!رقم) return;
    var تغيير = أحدث_تغيير[رقم] || {};
    var رصد = أحدث_رصد[رقم] || {};
    var تاريخ = تغيير.تاريخ || تاريخ_صالح(مركبة['تاريخ_آخر_تغيير_زيت']);
    var آخر_قراءة = تغيير.قراءة || قيمة_رقمية(مركبة['قراءة_عداد_آخر_تغيير_زيت']);
    var قراءة_حالية = Math.max(
      قيمة_رقمية(مركبة['آخر_قراءة_عداد'] || (Array.isArray(مركبة) ? مركبة[7] : 0)),
      قيمة_رقمية(رصد.قراءة)
    );
    if (!تاريخ) return;
    var فرق_أيام = Math.max(0, Math.floor((اليوم - تاريخ) / 86400000));
    var فرق_كم = Math.max(0, قراءة_حالية - آخر_قراءة);
    if (فرق_كم >= 4500 || فرق_أيام >= 25) {
      حسب_اللوحة[رقم] = {
        رقم: رقم,
        فرق_كم: فرق_كم,
        فرق_أيام: فرق_أيام,
        خطر: فرق_كم >= 5000 || فرق_أيام >= 30
      };
    }
  });
  return Object.keys(حسب_اللوحة).map(function(رقم) { return حسب_اللوحة[رقم]; })
    .sort(function(a, b) { return Number(b.خطر) - Number(a.خطر) || b.فرق_كم - a.فرق_كم || b.فرق_أيام - a.فرق_أيام; });
}

