function تطبيع_سجل_قادِم(سجل, نوع) {
  var ن = Object.assign({}, سجل || {});
  if (نوع === 'رصد') {
    if (!ن['الموقع']) ن['الموقع'] = ن['الموقع_الحالي'] || '';
    if (!ن['الحالة']) ن['الحالة'] = ن['حالة_المركبة'] || '';
  }
  if (نوع === 'حوادث') {
    if (!ن['نوع_الحادث']) ن['نوع_الحادث'] = ن['النوع'] || '';
    if (!ن['الأضرار']) ن['الأضرار'] = ن['الخسائر_التقديرية'] || '';
    if (!ن['الحالة']) ن['الحالة'] = ن['حالة_الطلب'] || '';
  }
  if (نوع === 'صيانة' && !ن['قطع_الغيار']) ن['قطع_الغيار'] = ن['قطعة_الغيار'] || '';
  return ن;
}

