// ====== مزامنة بيانات مركبة في الذاكرة المحلية ======
function تحديث_بيانات_مركبة_محلية(رقم_اللوحة, تغييرات) {
  if (!رقم_اللوحة) return null;
  var نتيجة = null;
  [بيانات_الاسطول_المحلية, قاعدة_بيانات_الاسطول].forEach(function(قائمة) {
    if (!Array.isArray(قائمة)) return;
    قائمة.forEach(function(مركبة) {
      var رقم = مركبة['رقم_اللوحة'] || (Array.isArray(مركبة) ? مركبة[0] : '');
      if (رقم !== رقم_اللوحة || Array.isArray(مركبة)) return;
      Object.keys(تغييرات).forEach(function(مفتاح) {
        if (تغييرات[مفتاح] !== '' && تغييرات[مفتاح] !== undefined && تغييرات[مفتاح] !== null) مركبة[مفتاح] = تغييرات[مفتاح];
      });
      if (!نتيجة) نتيجة = مركبة;
    });
  });
  return نتيجة;
}

